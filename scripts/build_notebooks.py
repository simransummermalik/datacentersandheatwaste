"""Create the three small audit notebooks from source-controlled templates."""

from __future__ import annotations

from pathlib import Path

import nbformat as nbf


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "notebooks"
OUT.mkdir(exist_ok=True)


def make_notebook(cells: list[object], name: str) -> None:
    notebook = nbf.v4.new_notebook(
        cells=cells,
        metadata={
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python", "version": "3"},
        },
    )
    with (OUT / name).open("w", encoding="utf-8") as handle:
        nbf.write(notebook, handle)


make_notebook(
    [
        nbf.v4.new_markdown_cell(
            "# 01 — Baseline heat-recovery scenarios\n\n"
            "This notebook reads the scenario CSV and the outputs generated by "
            "`scripts/generate_results.py`. The baseline is a transparent screening "
            "case, not a site prediction."
        ),
        nbf.v4.new_code_cell(
            "from pathlib import Path\n"
            "import pandas as pd\n"
            "ROOT = Path.cwd()\n"
            "if ROOT.name == 'notebooks': ROOT = ROOT.parent\n"
            "results = pd.read_csv(ROOT / 'results' / 'scenario_results.csv')\n"
            "results[['scenario_id','pathway','coolant_outlet_temp_c','outdoor_temp_c','heat_pump_cop','heat_pump_electric_mw','delivered_heat_mw','supported_area_m2']]"
        ),
        nbf.v4.new_markdown_cell(
            "## What to notice\n\n"
            "At 35 °C source temperature the baseline needs a heat pump for a 40 °C "
            "greenhouse supply plus a 5 °C direct-exchange approach. The electrical "
            "input is shown separately; the extra condenser heat is not free."
        ),
        nbf.v4.new_code_cell(
            "from IPython.display import Image, display\n"
            "display(Image(filename=str(ROOT / 'figures' / 'heat_flow_vs_it_load.png')))\n"
            "display(Image(filename=str(ROOT / 'figures' / 'energy_flow_checkpoints.png')))"
        ),
    ],
    "01_baseline.ipynb",
)

